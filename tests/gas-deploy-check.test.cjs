'use strict';
const {test} = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {execFileSync} = require('node:child_process');
const {check} = require('../scripts/check-gas-deploy.cjs');

test('deployment guard requires merged clean main and reviewed GAS manifest', t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'gas-deploy-'));
  t.after(() => fs.rmSync(root, {recursive: true, force: true}));
  const git = (...args) => execFileSync('git', args, {cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe']}).trim();
  git('init', '-b', 'main');
  fs.mkdirSync(path.join(root, 'GAS'));
  fs.writeFileSync(path.join(root, '.gitignore'), '.clasp.json\n');
  const manifest = path.join(root, 'GAS/appsscript.json');
  fs.writeFileSync(manifest, JSON.stringify({runtimeVersion: 'V8', timeZone: 'Asia/Taipei'}));
  git('add', '.');
  git('-c', 'user.name=Test', '-c', 'user.email=test@example.invalid', '-c', 'commit.gpgsign=false', 'commit', '-m', 'fixture');
  const head = git('rev-parse', 'HEAD');
  git('update-ref', 'refs/remotes/origin/main', head);
  assert.throws(() => check(root), /缺少 .clasp.json/);
  const config = path.join(root, '.clasp.json');
  const configure = (scriptId, rootDir = 'GAS') => fs.writeFileSync(config, JSON.stringify({scriptId, rootDir}));
  configure('REPLACE_WITH_SCRIPT_ID');
  assert.throws(() => check(root), /Script ID/);
  configure('test-script-id', '.');
  assert.throws(() => check(root), /rootDir/);
  configure('test-script-id');
  assert.equal(check(root), head);
  fs.writeFileSync(path.join(root, 'untracked.txt'), 'local change');
  assert.throws(() => check(root), /未提交變更/);
  fs.unlinkSync(path.join(root, 'untracked.txt'));
  git('switch', '-c', 'codex/change');
  assert.throws(() => check(root), /main/);
  git('switch', 'main');
  git('-c', 'user.name=Test', '-c', 'user.email=test@example.invalid', '-c', 'commit.gpgsign=false', 'commit', '--allow-empty', '-m', 'not merged');
  assert.throws(() => check(root), /origin\/main 不一致/);
});
